import assert from 'node:assert/strict';
import {neutralRegions} from '../slime-walk.js';
import {sampleKeys,putKey,readClip,restoreBase,baseDefaults} from '../slime-keyframes.js';
const motion={squash:1,stretch:1,lean:1,flow:1,lag:1};
let keys=[0,1].map(t=>({t,regions:neutralRegions()}));
const shape=sampleKeys(keys,.5);shape.regions[1].sx=.15;shape.regions[2].x=.4;
keys=putKey(keys,.5,shape);shape.regions[1].sx=2;
assert.equal(keys.length,3);assert.equal(sampleKeys(keys,0).regions[1].sx,1);
assert.equal(sampleKeys(keys,.5).regions[1].sx,.15);
assert.equal(sampleKeys(keys,1).regions[1].sx,1);
assert(Math.abs(sampleKeys(keys,.25).regions[1].sx-.575)<1e-9);
assert.equal(sampleKeys(keys,.25).regions[2].x,.2);
assert.deepEqual(sampleKeys(keys,.25),sampleKeys(keys,.75));
keys=putKey(keys,.5,sampleKeys(keys,.25));assert.equal(keys.length,3);
const clip={format:'slime-motion-keyframes',version:1,duration:.96,keys};assert.deepEqual(readClip(JSON.parse(JSON.stringify(clip))).keys,keys);
assert.throws(()=>readClip({...clip,keys:[keys[1],keys[2]]}));
assert.equal(sampleKeys(keys.filter(k=>k.t!==.5),.5).regions[1].sx,1);
console.log('PASS: local edits, interpolation, XYZ, replacement, deletion, save roundtrip, invalid endpoints');

const legacy={...baseDefaults,duration:1.4,squash:1.7,stretch:2.2};
const oldClip=readClip({format:'slime-motion-keyframes',version:1,duration:.96,keys:keys.map(k=>({...k,motion:{...motion}}))});
assert.deepEqual(restoreBase(legacy,null,oldClip),legacy);
const independent={...legacy,stretch:2.7};assert.deepEqual(restoreBase(legacy,independent,oldClip),independent);
const upgraded={format:'slime-motion-keyframes',version:2,duration:independent.duration,baseSettings:independent,keys};
assert.deepEqual(readClip(upgraded).baseSettings,independent);
assert(!('motion' in sampleKeys(keys,.25)));
const unchanged=JSON.stringify(keys),draft=sampleKeys(keys,.4);draft.regions[1].sx=.2;
assert.equal(JSON.stringify(keys),unchanged,'Draft must not change animation');
const committed=putKey(keys,.4,draft);assert.equal(committed.length,keys.length+1);assert.equal(JSON.stringify(keys),unchanged);
console.log('PASS: original base restored; global base independent; draft has no effect before explicit commit');
